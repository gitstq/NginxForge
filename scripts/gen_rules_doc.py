SEVERITY_ICON = {"error": "🔴", "warning": "🟡", "info": "🔵"}
CATEGORY_ORDER = {"correctness": 0, "security": 1, "performance": 2, "style": 3}


def build_markdown() -> str:
    load_default_rules()
    rules = sorted(RULES, key=lambda r: (CATEGORY_ORDER.get(r.category, 9), r.id))

    out = [
        "# 📋 NginxForge 规则目录 / Rule catalogue",
        "",
        "> 本文件由 `scripts/gen_rules_doc.py` 自动生成，请勿手工编辑。",
        "> Generated by `scripts/gen_rules_doc.py` — do not edit by hand.",
        "",
        f"共 **{len(rules)}** 条规则 · 用 `nginxforge rules <ID>` 查看单条规则的完整说明。",
        "",
        "| ID | Severity | Category | 标题（中） | Title (en) |",
        "| --- | --- | --- | --- | --- |",
    ]
    for r in rules:
        icon = SEVERITY_ICON.get(r.severity, "")
        zh = ZH_TITLES.get(r.id, r.title)
        out.append(
            f"| `{r.id}` | {icon} `{r.severity}` | `{r.category}` | {zh} | {r.title} |"
        )

    out += ["", "## 按类别统计 / By category", "",
            "| Category | 数量 | 编号段 |", "| --- | --- | --- |"]
    for cat in ("correctness", "security", "performance", "style"):
        ids = [r.id for r in rules if r.category == cat]
        if ids:
            out.append(f"| `{cat}` | {len(ids)} | `{ids[0]}` – `{ids[-1]}` |")

    missing = [r.id for r in rules if r.id not in ZH_TITLES]
    if missing:
        out += ["", "<!-- TODO: 以下规则缺少中文标题：" + ", ".join(missing) + " -->"]

    return "\n".join(out) + "\n"


def main() -> int:
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    target = os.path.join(root, "docs", "RULES.md")
    text = build_markdown()
    os.makedirs(os.path.dirname(target), exist_ok=True)
    with open(target, "w", encoding="utf-8") as fh:
        fh.write(text)
    print(f"wrote {target} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
